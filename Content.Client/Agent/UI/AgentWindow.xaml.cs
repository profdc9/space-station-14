using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client.Agent.UI;

/// <summary>
///     The copilot side panel: status line, conversation, input, notification feed.
/// </summary>
/// <remarks>
///     Everything the human or the agent writes goes through <see cref="FormattedMessage.AddText"/>,
///     never <c>AddMarkup</c>. Agent output is untrusted text as far as this control is concerned,
///     and so is anything the human pastes in — neither should be able to inject rich-text tags.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class AgentWindow : DefaultWindow
{
    private static readonly Color TimestampColor = Color.Gray;

    /// <summary>Raised when the human enters a line. The controller forwards it to the bridge.</summary>
    public event Action<string>? MessageEntered;

    public AgentWindow()
    {
        RobustXamlLoader.Load(this);

        InputEdit.OnTextEntered += OnTextEntered;
    }

    private void OnTextEntered(LineEdit.LineEditEventArgs args)
    {
        if (string.IsNullOrWhiteSpace(args.Text))
            return;

        MessageEntered?.Invoke(args.Text);
        InputEdit.Clear();
    }

    public void SetStatus(AgentConnectionState connection, AgentControlMode mode)
    {
        var msg = new FormattedMessage();

        msg.PushColor(ConnectionColor(connection));
        msg.AddText(Loc.GetString($"agent-connection-{connection.ToString().ToLowerInvariant()}"));
        msg.Pop();
        msg.AddText("  ");
        msg.AddText(Loc.GetString("agent-status-mode",
            ("mode", Loc.GetString($"agent-mode-{mode.ToString().ToLowerInvariant()}"))));

        StatusLabel.SetMessage(msg);
    }

    public void AddMessage(AgentMessage message)
    {
        var msg = new FormattedMessage();

        AddTimestamp(msg, message.At);

        msg.PushColor(SpeakerColor(message.Speaker));
        msg.AddText(Loc.GetString($"agent-speaker-{message.Speaker.ToString().ToLowerInvariant()}"));
        msg.AddText(" ");
        msg.AddText(message.Text);
        msg.Pop();

        ConversationOutput.AddMessage(msg);
    }

    public void AddNotification(AgentNotification notification)
    {
        var msg = new FormattedMessage();

        AddTimestamp(msg, notification.At);

        msg.PushColor(UrgencyColor(notification.Urgency));
        msg.AddText(notification.Text);
        msg.Pop();

        NotificationOutput.AddMessage(msg);
    }

    public void ClearAll()
    {
        ConversationOutput.Clear();
        NotificationOutput.Clear();
    }

    /// <summary>Puts the caret in the input box, so the toggle keybind lands ready to type.</summary>
    public void FocusInput()
    {
        InputEdit.GrabKeyboardFocus();
    }

    private static void AddTimestamp(FormattedMessage msg, DateTime at)
    {
        msg.PushColor(TimestampColor);
        msg.AddText($"{at:HH:mm:ss} ");
        msg.Pop();
    }

    private static Color ConnectionColor(AgentConnectionState connection) => connection switch
    {
        AgentConnectionState.Connected => Color.LimeGreen,
        AgentConnectionState.Connecting => Color.Yellow,
        _ => Color.DarkGray,
    };

    private static Color SpeakerColor(AgentSpeaker speaker) => speaker switch
    {
        AgentSpeaker.Human => Color.White,
        AgentSpeaker.Agent => Color.LightSkyBlue,
        _ => Color.DarkGray,
    };

    private static Color UrgencyColor(AgentUrgency urgency) => urgency switch
    {
        AgentUrgency.High => Color.OrangeRed,
        AgentUrgency.Low => Color.DarkGray,
        _ => Color.White,
    };
}
